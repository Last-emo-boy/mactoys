    @Test func stlBinaryEvenWithSolidHeader() throws {
        var data = Data("solid but actually binary".utf8)
        data.append(Data(count: 80 - data.count))
        data.append(le32(2))
        for tri in [[SIMD3<Float>(0, 0, 0), SIMD3(1, 0, 0), SIMD3(0, 1, 0)], [SIMD3(0, 0, 1), SIMD3(1, 0, 1), SIMD3(0, 1, 1)]] {
