    // MARK: Binary G-code

    @Test func heatshrinkBackReferences() {
        // "abc" as literals, then a back-reference of 6 bytes from 3 back: "abcabcabc".
        var w = BitWriter()
        for c in "abc".utf8 { w.put(1, 1); w.put(Int(c), 8) }
        w.put(0, 1); w.put(3 - 1, 11); w.put(6 - 1, 4)
        let out = Heatshrink.decode(w.bytes, windowBits: 11, lookaheadBits: 4, outputSize: 9)
        #expect(String(decoding: out, as: UTF8.self) == "abcabcabc")
    }

    @Test func meatPackUnpacksNibblesAndFullCharacters() {
        let packed: [UInt8] = [0xFF, 0xFF, 0xFB,   // enable packing
                               0x1D, 0xEB, 0x01, 0x0C,   // "G1", " X", "10", "\n"
                               0x8F, 0x4D, 0xC4]         // full 'M' + '8', then "4\n"
        #expect(String(decoding: MeatPack.decode(packed), as: UTF8.self) == "G1 X10\nM84\n")
    }

    @Test func bgcodeBlocks() throws {
        let png = try #require(onePixelPNG())
        var file = Data("GCDE".utf8)
        file.append(le32(1)); file.append(le16(0))                       // version 1, no checksum
        file.append(le16(5)); file.append(le16(0)); file.append(le32(png.count))
        file.append(le16(0)); file.append(le16(1)); file.append(le16(1)) // PNG 1×1
        file.append(png)
        let meta = Data("estimated printing time (normal mode)=12m 5s\n".utf8)
        file.append(le16(4)); file.append(le16(0)); file.append(le32(meta.count)); file.append(le16(0)); file.append(meta)
        let gcode = Data("G1 Z0.2\nG1 X10 Y0 E1\nG1 X10 Y10 E2\n".utf8)
        file.append(le16(1)); file.append(le16(0)); file.append(le32(gcode.count)); file.append(le16(0)); file.append(gcode)

        #expect(BGCode.isBGCode(file))
        let parsed = try BGCode.parse(file)
        #expect(parsed.thumbnails.count == 1 && parsed.thumbnails[0].format == .png)
        #expect(parsed.metadata["estimated printing time (normal mode)"] == "12m 5s")
        let path = try BGCode.toolpath(file)
        #expect(path.estimatedTime == "12m 5s")
        #expect(path.hasExtrusion && path.moveCount == 3)
        #expect(throws: BGCode.DecodeError.notBGCode) { try BGCode.parse(Data("G1 X1".utf8)) }
    }

