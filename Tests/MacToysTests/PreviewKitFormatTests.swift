    // MARK: Helpers

    private func onePixelPNG() -> Data? {
        guard let ctx = ImageUtil.context(width: 1, height: 1) else { return nil }
        ctx.setFillColor(CGColor(srgbRed: 1, green: 0.5, blue: 0, alpha: 1))
        ctx.fill(CGRect(x: 0, y: 0, width: 1, height: 1))
        return ctx.makeImage().flatMap(ImageUtil.pngData)
    }

    private func le16(_ v: Int) -> Data { Data([UInt8(v & 0xFF), UInt8(v >> 8 & 0xFF)]) }
    private func le32(_ v: Int) -> Data { Data((0..<4).map { UInt8(v >> ($0 * 8) & 0xFF) }) }
    private func le32f(_ f: Float) -> Data { le32(Int(f.bitPattern)) }
}

/// MSB-first bit packing for building heatshrink streams.
private struct BitWriter {
    var bytes: [UInt8] = []
    var bit = 0

    mutating func put(_ value: Int, _ count: Int) {
        for i in stride(from: count - 1, through: 0, by: -1) {
            if bit % 8 == 0 { bytes.append(0) }
            if value >> i & 1 == 1 { bytes[bytes.count - 1] |= UInt8(0x80 >> (bit % 8)) }
            bit += 1
        }
    }
}
