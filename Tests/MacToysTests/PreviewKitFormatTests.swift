    // MARK: QOI

    /// 3×2 image encoded by hand, one chunk of every kind.
    static let qoiBytes: [UInt8] = [
        0x71, 0x6F, 0x69, 0x66, 0, 0, 0, 3, 0, 0, 0, 2, 4, 0,    // "qoif", 3 × 2, RGBA, sRGB
        0xFE, 0xFF, 0x00, 0x00,                                 // OP_RGB   (255, 0, 0)
        0xC0,                                                   // OP_RUN   ×1
        0x5E,                                                   // OP_DIFF  dr −1, dg +1, db 0 → (254, 1, 0)
        0x32,                                                   // OP_INDEX 50 → (255, 0, 0)
        0xAA, 0x3A,                                             // OP_LUMA  dg +10, dr +5, db +12 → (4, 10, 12) (r wraps)
        0xFF, 0x10, 0x20, 0x30, 0x80,                           // OP_RGBA  (16, 32, 48, 128)
        0, 0, 0, 0, 0, 0, 0, 1,                                 // end marker
    ]

    @Test func qoiDecodesEveryOpcode() throws {
        let (header, px) = try QOI.decodeRGBA(Data(Self.qoiBytes))
        #expect(header == QOI.Header(width: 3, height: 2, channels: 4, colorspace: 0))
        let pixels = stride(from: 0, to: px.count, by: 4).map { Array(px[$0..<($0 + 4)]) }
        #expect(pixels == [[255, 0, 0, 255], [255, 0, 0, 255], [254, 1, 0, 255],
                           [255, 0, 0, 255], [4, 10, 12, 255], [16, 32, 48, 128]])
        let image = try QOI.image(Data(Self.qoiBytes))
        #expect(image.width == 3 && image.height == 2)
    }

    @Test func qoiRejectsBadInput() {
        #expect(throws: QOI.DecodeError.notQOI) { try QOI.header(Data("nope-not-a-qoi".utf8)) }
        var bad = Self.qoiBytes
        bad[12] = 5
        #expect(throws: QOI.DecodeError.invalidHeader) { try QOI.header(Data(bad)) }
        var huge = Self.qoiBytes
        huge.replaceSubrange(4..<12, with: [0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF])
        #expect(throws: QOI.DecodeError.tooLarge) { try QOI.header(Data(huge)) }
    }

    // MARK: G-code

    @Test func gcodeMovesLayersArcsAndExtrusion() {
        let path = GCodeParser.parse("""
        ; generated by PrusaSlicer 2.7.1 on 2026-01-01
        G21 ; mm
        G90
        M82
        G1 Z0.2 F1200
        G1 X10 Y0 E1
        G1 X10 Y10 E2.5 ; comment
        G0 X0 Y0
        G1 Z0.4
        G1X5Y5E3      (no spaces)
        G2 X15 Y5 I5 J0 E4
        G92 E0
        G1 X20 E1
        ; estimated printing time (normal mode) = 1h 2m 3s
        """)
        #expect(path.slicer == "PrusaSlicer 2.7.1")
        #expect(path.estimatedTime == "1h 2m 3s")
        #expect(path.hasExtrusion)
        #expect(path.layerCount == 2)
        #expect(abs(path.filamentMM - 5) < 1e-6)
        let arcPoints = path.kinds.filter { $0 == .extrude }.count
        #expect(arcPoints > 6)                          // the half circle became several segments
        let b = path.bounds
        #expect(b?.min.x == 0 && b?.max.x == 20)
        #expect(abs((b?.max.y ?? 0) - 10) < 1e-4)
        // The arc bulges to y = 0 below its center (10, 5): clockwise from (5,5) to (15,5) passes y = 10.
        #expect(path.ys.contains { abs($0 - 10) < 0.05 })
    }

