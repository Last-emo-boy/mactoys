    import Foundation

    /// Counts words in a file, ignoring punctuation.
    struct WordCounter {
        let url: URL
        var minimumLength = 2

        func count() throws -> [String: Int] {
            let text = try String(contentsOf: url, encoding: .utf8)
            var totals: [String: Int] = [:]
            for word in text.split(whereSeparator: { !$0.isLetter }) where word.count >= minimumLength {
                totals[word.lowercased(), default: 0] += 1   // case-insensitive
            }
            return totals
        }
    }

    @main
    enum Main {
        static func main() throws {
            let counter = WordCounter(url: URL(fileURLWithPath: "README.md"))
            let top = try counter.count().sorted { $0.value > $1.value }.prefix(10)
            for (word, n) in top { print("\\(word): \\(n)") }
        }
    }
