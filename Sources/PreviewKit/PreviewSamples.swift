    /// A twisted, bulging vase: 150 layers of 0.2 mm, each a rounded square.
    public static func vaseGCode() -> String {
        var lines = ["; generated by PrusaSlicer 2.8.1 on 2026-10-24", "G21", "G90", "M82", "G28", "G92 E0"]
        var e = 0.0
        let layers = 150
        for layer in 0..<layers {
            let z = 0.2 * Double(layer + 1)
            let t = Double(layer) / Double(layers)
            let radius = 18 + 7 * sin(t * .pi * 1.2)
            let twist = t * .pi / 2.5
            lines.append("G1 Z\(String(format: "%.2f", z)) F1200")
            let steps = 64
            for s in 0...steps {
                let a = Double(s) / Double(steps) * 2 * .pi
                // Superellipse for a rounded-square outline.
                let c = cos(a), sn = sin(a)
                let r = radius / pow(pow(abs(c), 4) + pow(abs(sn), 4), 0.25)
                let x = 100 + r * cos(a + twist), y = 100 + r * sin(a + twist)
                if s == 0 { lines.append(String(format: "G0 X%.3f Y%.3f", x, y)); continue }
                e += 0.06
                lines.append(String(format: "G1 X%.3f Y%.3f E%.4f", x, y, e))
            }
        }
        lines.append("; estimated printing time (normal mode) = 1h 18m 40s")
        return lines.joined(separator: "\n")
    }

    /// A gear-like ring mesh (about 6 000 triangles).
    public static func gearMesh() -> STLMesh {
        var mesh = STLMesh()
        mesh.name = "gear"
        let teeth = 18, seg = teeth * 8
        let height: Float = 8
        func outer(_ i: Int) -> Float {
            let phase = (i % 8)
            return phase < 4 ? 30 : 26
        }
        let inner: Float = 12
        func point(_ i: Int, _ r: Float, _ z: Float) -> SIMD3<Float> {
            let a = Float(i) / Float(seg) * 2 * .pi
            return SIMD3(r * cos(a), r * sin(a), z)
        }
        func quad(_ a: SIMD3<Float>, _ b: SIMD3<Float>, _ c: SIMD3<Float>, _ d: SIMD3<Float>) {
            mesh.vertices += [a, b, c, a, c, d]
        }
        for i in 0..<seg {
            let j = (i + 1) % seg
            let ro = outer(i), rn = outer(j)
            // Top and bottom faces.
            quad(point(i, inner, height), point(i, ro, height), point(j, rn, height), point(j, inner, height))
            quad(point(j, inner, 0), point(j, rn, 0), point(i, ro, 0), point(i, inner, 0))
            // Outer wall, including the tooth flanks.
            quad(point(i, ro, 0), point(j, ro, 0), point(j, ro, height), point(i, ro, height))
            if ro != rn {
                quad(point(j, ro, 0), point(j, rn, 0), point(j, rn, height), point(j, ro, height))
            }
            // Inner wall.
            quad(point(j, inner, 0), point(i, inner, 0), point(i, inner, height), point(j, inner, height))
        }
        return mesh
    }

    /// A warm sunset gradient photo stand-in (like the design boards).
    public static func gradientImage(width: Int = 1200, height: Int = 800) -> CGImage? {
        guard let ctx = ImageUtil.context(width: width, height: height) else { return nil }
        let colors = [CGColor(srgbRed: 0.98, green: 0.73, blue: 0.42, alpha: 1), CGColor(srgbRed: 0.96, green: 0.52, blue: 0.38, alpha: 1),
                      CGColor(srgbRed: 0.38, green: 0.36, blue: 0.90, alpha: 1)] as CFArray
        guard let gradient = CGGradient(colorsSpace: ImageUtil.sRGB, colors: colors, locations: [0, 0.5, 1]) else { return nil }
        ctx.drawLinearGradient(gradient, start: CGPoint(x: 0, y: CGFloat(height)), end: CGPoint(x: CGFloat(width) * 0.6, y: 0),
                               options: [.drawsBeforeStartLocation, .drawsAfterEndLocation])
        return ctx.makeImage()
    }
