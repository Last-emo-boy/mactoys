import AppKit
import Foundation
import MacToysCore
import UniformTypeIdentifiers

/// Watches the general pasteboard for copied images (polling `changeCount` twice a second, which is
/// cheap) and reads clipboard images on demand.
@MainActor
final class ClipboardWatcher {
    /// A copied image: its best data representation and type.
    var onImage: (Data, UTType) -> Void = { _, _ in }
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            MainActor.assumeIsolated { [weak self] in self?.poll() }
        }
        timer?.tolerance = 0.2
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Call after MacToys writes the pasteboard so the write isn't optimized again.
    func noteOwnWrite() {
        lastChange = NSPasteboard.general.changeCount
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard let types = pb.types, Self.isPlainImageCopy(types.map(\.rawValue)),
              let (data, type) = Self.image(on: pb) else { return }
        onImage(data, type)
    }

    /// Pasteboard types that mean "leave this alone": passwords, transient data, and copies that also
    /// carry text or files (a web page selection, a Finder copy), where replacing everything with an
    /// image would lose something.
    static func isPlainImageCopy(_ types: [String]) -> Bool {
        let skip: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                 "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        if types.contains(where: skip.contains) { return false }
        let text: Set<String> = [NSPasteboard.PasteboardType.string.rawValue, NSPasteboard.PasteboardType.html.rawValue,
                                 NSPasteboard.PasteboardType.rtf.rawValue, NSPasteboard.PasteboardType.fileURL.rawValue,
                                 "public.url", "NSFilenamesPboardType"]
        if types.contains(where: text.contains) { return false }
        return types.contains { id in UTType(id)?.conforms(to: .image) ?? false }
    }

    /// The image on the pasteboard: PNG, JPEG or HEIC as is, otherwise TIFF (what screenshots and most
    /// apps put there).
    static func image(on pb: NSPasteboard) -> (Data, UTType)? {
        for type in [UTType.png, .jpeg, .heic, .tiff] {
            if let data = pb.data(forType: NSPasteboard.PasteboardType(type.identifier)), !data.isEmpty {
                return (data, type)
            }
        }
        return nil
    }

    /// Writes an optimized image back as the clipboard's only content.
    func write(_ data: Data, type: UTType) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setData(data, forType: NSPasteboard.PasteboardType(type.identifier))
        noteOwnWrite()
        if ClipboardHistory.shared.isRunning { ClipboardHistory.shared.ignoreNextChange = true }
    }
}

/// Notices file drags anywhere on screen and reports when the pointer heads into a screen corner,
/// where the drop zone appears.
///
/// A global mouse-dragged monitor (no permission needed for mouse events) checks the drag pasteboard
/// once per drag, at most every 80 ms during its first second; afterwards each event is a cheap
/// rectangle test.
@MainActor
final class DragWatcher {
    var corner: ScreenCorner = .bottomRight
    var acceptedKinds: (URL) -> Bool = { _ in true }
    /// The pointer entered or left the corner region during a file drag.
    var onCorner: (_ inside: Bool, _ screen: NSScreen) -> Void = { _, _ in }
    var onDragEnd: () -> Void = {}

    private var monitor: Any?
    private let dragPasteboard = NSPasteboard(name: .drag)
    private var lastDragChange = 0
    private var dragStarted: Date?
    private var lastCheck = Date.distantPast
    private var isFileDrag: Bool?
    private var inCorner = false

    var isRunning: Bool { monitor != nil }

    func start() {
        guard monitor == nil else { return }
        lastDragChange = dragPasteboard.changeCount
        monitor = NSEvent.addGlobalMonitorForEvents(matching: [.leftMouseDragged, .leftMouseUp]) { event in
            let type = event.type
            MainActor.assumeIsolated { [weak self] in self?.handle(type) }
        }
    }

    func stop() {
        if let monitor { NSEvent.removeMonitor(monitor) }
        monitor = nil
        reset()
    }

    private func reset() {
        dragStarted = nil
        isFileDrag = nil
        if inCorner {
            inCorner = false
            onDragEnd()
        }
    }

    private func handle(_ type: NSEvent.EventType) {
        guard type == .leftMouseDragged else {
            reset()
            return
        }
        let now = Date()
        if dragStarted == nil { dragStarted = now }
        if isFileDrag == nil {
            guard now.timeIntervalSince(lastCheck) > 0.08 else { return }
            lastCheck = now
            let count = dragPasteboard.changeCount
            if count != lastDragChange {
                lastDragChange = count
                isFileDrag = hasAcceptedFiles()
            } else if let started = dragStarted, now.timeIntervalSince(started) > 1 {
                isFileDrag = false   // a window move or text selection, not a file drag
            }
        }
        guard isFileDrag == true else { return }
        let point = NSEvent.mouseLocation
        guard let screen = NSScreen.screens.first(where: { $0.frame.contains(point) }) else { return }
        let inside = Self.cornerRegion(corner, in: screen.frame, expanded: inCorner).contains(point)
        if inside != inCorner {
            inCorner = inside
            onCorner(inside, screen)
        }
    }

    private func hasAcceptedFiles() -> Bool {
        let urls = dragPasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        return urls.contains(where: acceptedKinds)
    }

    /// The area of a screen that counts as "toward the corner": about a third of its width and height,
    /// a little larger once inside so the zone doesn't flicker at the edge.
    static func cornerRegion(_ corner: ScreenCorner, in frame: CGRect, expanded: Bool = false) -> CGRect {
        let grow: CGFloat = expanded ? 1.25 : 1
        let w = max(320, frame.width * 0.3) * grow
        let h = max(280, frame.height * 0.35) * grow
        let x = corner.isLeft ? frame.minX : frame.maxX - w
        let y = corner.isTop ? frame.maxY - h : frame.minY   // Cocoa: y grows upward
        return CGRect(x: x, y: y, width: w, height: h)
    }
}
